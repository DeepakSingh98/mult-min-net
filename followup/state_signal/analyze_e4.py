"""analyze_e4.py SCAN_DIR TRAIN_DIR > results/e4_tables.md: Experiment 4 numbers from raw JSON, read by the rule frozen in PROTOCOL.md (amendment of ~09:20 UTC)."""
import glob
import json
import os
import sys

import numpy as np

NETS = ("anylen", "two")


def load(d):
    return [json.load(open(f)) for f in glob.glob(os.path.join(d, "*.json"))] if d and os.path.isdir(d) else []


def boot(x, seed=11, B=4000):
    x = np.asarray(x, float)
    if len(x) == 0:
        return None, None, None
    g = np.random.default_rng(seed)
    m = np.median(x[g.integers(0, len(x), (B, len(x)))], axis=1)
    return float(np.median(x)), float(np.quantile(m, 0.025)), float(np.quantile(m, 0.975))


def f(v):
    return "" if v is None else f"{v:.3g}"


def main():
    sc, tr = load(sys.argv[1]), load(sys.argv[2] if len(sys.argv) > 2 else None)
    print("# Experiment 4 tables\n\nGenerated by `analyze_e4.py`. `base` clean weights; `scaled` `lnf.w` and `lnf.b` times alpha (5.2 `anylen`, 6.72 `two`). fp32.\n")
    print("## Start points\n\n| net | cond | CE | gradient norm | cosine of CE gradient with gain direction | strict |\n|---|---|---:|---:|---:|---|")
    for net in NETS:
        for cond in ("base", "scaled"):
            rs = [r for r in sc if r["case"]["net"] == net and r["case"]["cond"] == cond]
            if rs:
                print(f"| {net} | {cond} | {np.mean([r['ce0'] for r in rs]):.4f} | {np.median([r['g_norm'] for r in rs]):.3g} | {np.median([r['cos_grad_gain'] for r in rs]):.2e} | {all(r['base_ok'] for r in rs)} |")
    print("\n## Matched step scan\n\neps* is the largest L2 weight distance along a unit direction with strict 1.0 before first failure; `>` marks directions that never failed up to 1e6. Median over 8 gradient batches. `lowest CE` is the lowest CE at a passing point on the line. `moved` the entries actually changed at eps*, because a move below one float32 unit is lost to rounding.\n")
    print("| net | direction | base eps* | scaled eps* | ratio [95% CI] | base lowest CE | scaled lowest CE | base moved | scaled moved | fails at length |\n|---|---|---:|---:|---|---:|---:|---:|---:|---|")
    read = {}
    for net in NETS:
        b = {r["case"]["grad_seed"]: r for r in sc if r["case"]["net"] == net and r["case"]["cond"] == "base"}
        s = {r["case"]["grad_seed"]: r for r in sc if r["case"]["net"] == net and r["case"]["cond"] == "scaled"}
        keys = sorted(set(b) & set(s))
        if not keys:
            continue
        for d in b[keys[0]]["rows"]:
            eb = [b[k]["rows"][d]["eps_star"] for k in keys]
            es = [s[k]["rows"][d]["eps_star"] for k in keys]
            cb = sum(b[k]["rows"][d]["censored"] for k in keys)
            cs = sum(s[k]["rows"][d]["censored"] for k in keys)
            ratio = boot([y / max(x, 1e-300) for x, y in zip(eb, es)])
            if d == "grad":
                read[net] = dict(eps=ratio)
            fl = sorted({str(r["rows"][d]["fail_len"]) for r in list(b.values()) + list(s.values())})
            print(f"| {net} | {d} | {'>' if cb else ''}{np.median(eb):.3g} | {'>' if cs else ''}{np.median(es):.3g} | {f(ratio[0])} [{f(ratio[1])}, {f(ratio[2])}] | {np.median([b[k]['rows'][d]['min_ce'] for k in keys]):.4g} | {np.median([s[k]['rows'][d]['min_ce'] for k in keys]):.4g} | {int(np.median([b[k]['rows'][d]['moved_at_star'] for k in keys]))} | {int(np.median([s[k]['rows'][d]['moved_at_star'] for k in keys]))} | {', '.join(fl)} |")
    print("\n## SGD and Adam\n\nEach row: same lr, scope and seeds in both conditions, 3 seeds. `fail` median step of first strict failure, `none` for no failure by 2,000 steps. `D` median displacement at the last passing check. Adam normalizes gradient scale, so a scaled net could die under it for that alone: it takes no part in the read.\n")
    print("| net | opt | scope | lr | base fails | scaled fails | base fail step | scaled fail step | base D | scaled D | base CE at last pass | scaled CE at last pass |\n|---|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|")
    idx = {}
    for r in tr:
        c = r["case"]
        idx.setdefault((c["net"], c["opt"], c["scope"], c["lr"]), {}).setdefault(c["cond"], {})[c["seed"]] = r
    for k in sorted(idx, key=lambda x: (NETS.index(x[0]), x[1], x[2], x[3])):
        v = idx[k]
        cell = []
        for cond in ("base", "scaled"):
            rs = list(v.get(cond, {}).values())
            fs = [r["fail_step"] for r in rs if r["fail_step"]]
            cell.append((f"{len(fs)}/{len(rs)}", f(float(np.median(fs))) if fs else "none", f(float(np.median([r["disp_ok"] for r in rs]))) if rs else "", f(float(np.median([r["ce_ok"] for r in rs]))) if rs else ""))
        print(f"| {k[0]} | {k[1]} | {k[2]} | {k[3]:g} | {cell[0][0]} | {cell[1][0]} | {cell[0][1]} | {cell[1][1]} | {cell[0][2]} | {cell[1][2]} | {cell[0][3]} | {cell[1][3]} |")
    print("\n## Frozen read\n\n`R_eps`: eps*(scaled) / eps*(base) along `grad`. `R_D`: D(scaled) / D(base) under SGD on pairs where both failed before the cap. `confidence implicated`: a lower bound at least 3. `sensitivity`: both intervals inside [1/3, 3]. `mixed`: anything else.\n")
    print("| net | R_eps [95% CI] | R_D [95% CI] | pairs both failed | base only failed | scaled only failed | neither | read |\n|---|---|---|---:|---:|---:|---:|---|")
    for net in NETS:
        if net not in read:
            continue
        ratios, bo, so, ne = [], 0, 0, 0
        for k, v in idx.items():
            if k[0] != net or k[1] != "sgd":
                continue
            for seed in v.get("base", {}):
                if seed not in v.get("scaled", {}):
                    continue
                x, y = v["base"][seed], v["scaled"][seed]
                if x["fail_step"] and y["fail_step"]:
                    if x["disp_ok"] > 0 and y["disp_ok"] > 0:
                        ratios.append(y["disp_ok"] / x["disp_ok"])
                elif x["fail_step"]:
                    bo += 1
                elif y["fail_step"]:
                    so += 1
                else:
                    ne += 1
        e, d = read[net]["eps"], boot(ratios)
        conf = (e[1] is not None and e[1] >= 3) or (d[1] is not None and d[1] >= 3)
        sens = e[1] is not None and d[1] is not None and 1 / 3 <= e[1] and e[2] <= 3 and 1 / 3 <= d[1] and d[2] <= 3
        rd = "confidence implicated" if conf else ("sensitivity" if sens else "mixed")
        print(f"| {net} | {f(e[0])} [{f(e[1])}, {f(e[2])}] | {f(d[0])} [{f(d[1])}, {f(d[2])}] | {len(ratios)} | {bo} | {so} | {ne} | **{rd}** |")


if __name__ == "__main__":
    main()
