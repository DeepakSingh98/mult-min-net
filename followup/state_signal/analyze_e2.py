"""analyze_e2.py select DEV_DIR > specs/e2_chosen.json: the frozen lr and tau rule on dev draws.
analyze_e2.py tables DIAG_DIR SCORED_DIR > results/e2_tables.md: Experiment 2 numbers from raw JSON, read by the rules in PROTOCOL.md."""
import glob
import itertools
import json
import os
import sys

import numpy as np
from scipy import stats

CELLS = ("p", "n1", "n2", "z1", "z4", "s1")
NETS = ("anylen", "two")
LOSSES = ("ce", "hinge")
RULES = ("std", "sur")
SUPP = ("all", "nz")
COUNTS = dict(anylen=(139440, 870), two=(231658, 487))


def load(d):
    out = []
    for f in glob.glob(os.path.join(d, "*.json")):
        out.append(json.load(open(f)))
    return out


def select(d):
    groups = {}
    for r in load(d):
        c = r["case"]
        groups.setdefault(f"{c['net']}|{c['cell']}|{c['loss']}-{c['rule']}-{c['supp']}", {}).setdefault((c["lr"], c["tau"]), []).append(r)
    chosen = {}
    for arm, by in groups.items():
        rows = []
        for (lr, tau), rs in by.items():
            rows.append((np.mean([r["kept"]["restored"] for r in rs]), np.mean([r["kept"]["L4"] for r in rs]), -lr, lr, tau, len(rs)))
        rows.sort(key=lambda x: (x[0], x[1], x[2]))
        b = rows[-1]
        chosen[arm] = dict(lr=b[3], tau=b[4], dev_restored=float(b[0]), dev_acc=float(b[1]), draws=b[5], grid=[[float(x[0]), float(x[1]), x[3], x[4]] for x in rows])
    print(json.dumps(chosen, indent=0))


def mcnemar(a, b):
    """exact two-sided: a, b paired booleans."""
    x = int(sum(u and not v for u, v in zip(a, b)))
    y = int(sum(v and not u for u, v in zip(a, b)))
    n = x + y
    return 1.0 if n == 0 else min(1.0, float(stats.binomtest(min(x, y), n, 0.5).pvalue))


def holm(ps):
    """dict key -> p, adjusted."""
    keys = sorted(ps, key=ps.get)
    adj, run = {}, 0.0
    for i, k in enumerate(keys):
        run = max(run, min(1.0, (len(keys) - i) * ps[k]))
        adj[k] = run
    return adj


def compare(data, factor, levels):
    """data: arm tuple -> {draw: restored}. Paired test of levels[1] minus levels[0] with the other factors held, Holm over every (net, cell, other levels)."""
    rows, ps = [], {}
    idx = dict(loss=0, rule=1, supp=2)[factor]
    others = [(LOSSES, RULES, SUPP)[i] for i in range(3) if i != idx]
    for net, cell, o in itertools.product(NETS, CELLS, itertools.product(*others)):
        arm = list(o)
        a0 = tuple(arm[:idx] + [levels[0]] + arm[idx:])
        a1 = tuple(arm[:idx] + [levels[1]] + arm[idx:])
        d0, d1 = data.get((net, cell) + a0), data.get((net, cell) + a1)
        if not d0 or not d1:
            continue
        draws = sorted(set(d0) & set(d1))
        u, v = [d0[x] for x in draws], [d1[x] for x in draws]
        key = (net, cell) + tuple(o)
        ps[key] = mcnemar(u, v)
        rows.append((key, float(np.mean(u)), float(np.mean(v)), len(draws)))
    adj = holm(ps) if ps else {}
    return [(k, a, b, n, ps[k], adj[k]) for k, a, b, n in rows]


def tables(diag_dir, sc_dir):
    print("# Experiment 2 tables\n\nGenerated by `analyze_e2.py` from `results/e2*/`. No result here is from a dev draw. Restored = strict 1.0 on fresh problems at length 4 (4,096), plus 20 (256) and 100 (32) for `anylen`.\n")
    dg = load(diag_dir)
    print("## At the damaged point, no optimizer\n\nMeans over draws. `cos`: cosine between the negative gradient and (clean - damaged), all entries. `cos nz`: same on the support. `on zeros`: share of squared gradient on zero entries. `rank`: median rank of the damaged entry by gradient size (1 = largest).\n")
    print("`rms 0` and `rms sup`: rms gradient per coordinate on zero entries and on support entries (`anylen` 138,570 and 870 coordinates, `two` 231,171 and 487).\n")
    print("| net | cell | start acc | loss | rule | |g| | cos | cos nz | on zeros | rms 0 | rms sup | rank | of |\n|---|---|---:|---|---|---:|---:|---:|---:|---:|---:|---:|---:|")
    for net in NETS:
        for cell in CELLS:
            rs = [r for r in dg if r["case"]["net"] == net and r["case"]["cell"] == cell]
            if not rs:
                continue
            acc = np.mean([r["acc"][0] for r in rs])
            for loss in LOSSES:
                for rule in RULES:
                    x = [row for r in rs for row in r["rows"] if row["loss"] == loss and row["rule"] == rule]
                    ranks = [q for row in x for q in row.get("ranks", [])]
                    N, Ns = COUNTS[net]
                    r0 = np.nanmean([row["g"] * np.sqrt(max(row["zero_share"], 0) / (N - Ns)) for row in x])
                    rsup = np.nanmean([row["g"] * np.sqrt(max(1 - row["zero_share"], 0) / Ns) for row in x])
                    print(f"| {net} | {cell} | {acc:.3f} | {loss} | {rule} | {np.nanmean([row['g'] for row in x]):.3g} | {np.nanmean([row['cos'] for row in x]):.2e} | {np.nanmean([row['cos_nz'] for row in x]):.2e} | {np.nanmean([row['zero_share'] for row in x]):.3f} | {r0:.3g} | {rsup:.3g} | {int(np.median(ranks)) + 1 if ranks else ''} | {x[0].get('entries', '')} |")
    print("\n## Straight line from damaged to clean\n\nStrict accuracy along damaged + beta (clean - damaged), mean over draws. Loss is mean CE.\n")
    print("| net | cell | " + " | ".join(f"{b / 10:.1f}" for b in range(11)) + " |\n|---|---|" + "---:|" * 11)
    for net in NETS:
        for cell in CELLS:
            rs = [r for r in dg if r["case"]["net"] == net and r["case"]["cell"] == cell]
            if rs:
                print(f"| {net} | {cell} | " + " | ".join(f"{np.mean([r['line'][b]['acc'] for r in rs]):.2f}" for b in range(11)) + " |")
    print("\n| net | cell | hinge at 0 | at 0.5 | at 0.9 | at 1.0 |\n|---|---|---:|---:|---:|---:|")
    for net in NETS:
        for cell in CELLS:
            rs = [r for r in dg if r["case"]["net"] == net and r["case"]["cell"] == cell]
            if rs:
                print(f"| {net} | {cell} | " + " | ".join(f"{np.mean([r['line'][b]['hinge'] for r in rs]):.3g}" for b in (0, 5, 9, 10)) + " |")
    sc = load(sc_dir)
    data, acc, left, dist = {}, {}, {}, {}
    for r in sc:
        c = r["case"]
        k = (c["net"], c["cell"], c["loss"], c["rule"], c["supp"])
        data.setdefault(k, {})[c["draw"]] = bool(r["kept"]["restored"])
        acc.setdefault(k, []).append(r["kept"]["L4"])
        left.setdefault(k, []).append(bool(r["kept"]["restored"]) and not bool(r["last"]["restored"]))
        dist.setdefault(k, []).append(r["dist_kept"] / max(r["dist_start"], 1e-30))
    print("\n## Scored repair\n\nRestored share over draws; mean strict accuracy at length 4 of the kept checkpoint; `left` share restored at the kept checkpoint and not at the last step; `dist` kept distance to the clean weights over starting distance, median.\n")
    print("| net | cell | loss | rule | supp | lr | tau | draws | restored | acc | left | dist |\n|---|---|---|---|---|---:|---:|---:|---:|---:|---:|---:|")
    for k in sorted(data, key=lambda x: (NETS.index(x[0]), CELLS.index(x[1]), x[2:])):
        c = next(r["case"] for r in sc if (r["case"]["net"], r["case"]["cell"], r["case"]["loss"], r["case"]["rule"], r["case"]["supp"]) == k)
        print(f"| {k[0]} | {k[1]} | {k[2]} | {k[3]} | {k[4]} | {c['lr']:g} | {c['tau']} | {len(data[k])} | {np.mean(list(data[k].values())):.3f} | {np.mean(acc[k]):.3f} | {np.mean(left[k]):.3f} | {np.median(dist[k]):.3g} |")
    print("\n## Amendment 3: only the damaged entries may move\n\nPost hoc, an oracle no learner has. Restored share over draws, with the same-draw McNemar test of `sur` against `std`, not corrected and exploratory.\n")
    print("| net | cell | loss | std lr | sur lr, tau | std restored | sur restored | std acc | sur acc | difference | McNemar p |\n|---|---|---|---:|---|---:|---:|---:|---:|---:|---:|")
    for net in NETS:
        for cell in CELLS:
            for loss in LOSSES:
                ks, ku = (net, cell, loss, "std", "dmg"), (net, cell, loss, "sur", "dmg")
                if ks not in data or ku not in data:
                    continue
                cs = next(r["case"] for r in sc if (r["case"]["net"], r["case"]["cell"], r["case"]["loss"], r["case"]["rule"], r["case"]["supp"]) == ks)
                cu = next(r["case"] for r in sc if (r["case"]["net"], r["case"]["cell"], r["case"]["loss"], r["case"]["rule"], r["case"]["supp"]) == ku)
                dr = sorted(set(data[ks]) & set(data[ku]))
                u, v = [data[ks][x] for x in dr], [data[ku][x] for x in dr]
                print(f"| {net} | {cell} | {loss} | {cs['lr']:g} | {cu['lr']:g}, {cu['tau']} | {np.mean(u):.3f} | {np.mean(v):.3f} | {np.mean(acc[ks]):.3f} | {np.mean(acc[ku]):.3f} | {np.mean(v) - np.mean(u):+.3f} | {mcnemar(u, v):.4f} |")
    print("\n## Frozen reads\n")
    ctl = [(k, np.mean(list(v.values()))) for k, v in data.items() if k[1] == "p" and k[3] == "std"]
    for net in NETS:
        b = max([v for k, v in ctl if k[0] == net and k[4] != "dmg"], default=None)
        d = max([v for k, v in ctl if k[0] == net and k[4] == "dmg"], default=None)
        print(f"Control `p`, {net}: best frozen `std` arm restored {'none' if b is None else format(b, '.3f')}; rule needs 0.5 in some arm: {'pass' if b is not None and b >= 0.5 else 'fail'}. Best `dmg` arm (amendment 3): {'none' if d is None else format(d, '.3f')}.\n")
    for name, factor, lv, thr in (("Surrogate helps (`sur` minus `std`)", "rule", RULES, 0.25), ("Hinge against CE", "loss", LOSSES, 0.25), ("Support only against all entries", "supp", SUPP, 0.25)):
        rows = compare(data, factor, lv)
        print(f"### {name}\n\n| net | cell | held | {lv[0]} | {lv[1]} | difference | McNemar p | Holm p | pass |\n|---|---|---|---:|---:|---:|---:|---:|---|")
        n_pass = 0
        for k, a, b, n, p, ad in sorted(rows, key=lambda x: (NETS.index(x[0][0]), CELLS.index(x[0][1]), x[0][2:])):
            ok = b - a >= thr and ad < 0.05
            n_pass += ok
            print(f"| {k[0]} | {k[1]} | {'/'.join(k[2:])} | {a:.3f} | {b:.3f} | {b - a:+.3f} | {p:.4f} | {ad:.4f} | {'**yes**' if ok else 'no'} |")
        print(f"\nCells passing: {n_pass} of {len(rows)}.\n")


def sweep(d):
    """post hoc: anylen z1, only the damaged entry free, every lr, the same 12 scored draws."""
    rs = load(d)
    print("Post hoc (amendment 5): `anylen` `z1`, only the lesioned entry free, the same 12 scored draws, 500 steps. Restored count of 12 by lr.\n")
    lrs = sorted({r["case"]["lr"] for r in rs})
    print("| loss | rule | tau | " + " | ".join(f"{x:g}" for x in lrs) + " | best |\n|---|---|---|" + "---:|" * (len(lrs) + 1))
    for loss in LOSSES:
        for rule, taus in (("std", [None]), ("sur", [0.5, 2.0])):
            for tau in taus:
                row = []
                for lr in lrs:
                    x = [r for r in rs if r["case"]["loss"] == loss and r["case"]["rule"] == rule and r["case"]["tau"] == tau and r["case"]["lr"] == lr]
                    row.append(sum(r["kept"]["restored"] for r in x) if x else None)
                print(f"| {loss} | {rule} | {tau} | " + " | ".join("" if v is None else str(v) for v in row) + f" | {max(v for v in row if v is not None)} |")


if __name__ == "__main__":
    if sys.argv[1] == "select":
        select(sys.argv[2])
    elif sys.argv[1] == "sweep":
        sweep(sys.argv[2])
    else:
        tables(sys.argv[2], sys.argv[3])
