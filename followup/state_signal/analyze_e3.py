"""analyze_e3.py RESULTS_DIR > results/e3_tables.md: Experiment 3 numbers from the raw JSON, read by the gates frozen in PROTOCOL.md. Means over checkpoints with t intervals."""
import glob
import json
import os
import sys

import numpy as np
from scipy import stats

ARMS = ("hints", "lathints", "lat", "latanneal", "nohint", "teacher")
SIZES = (16, 64, 128)
MASKS = ("p", "r", "i", "j")


def load(d):
    rows = {}
    for f in glob.glob(os.path.join(d, "*-n*-s*.json")):
        r = json.load(open(f))
        rows[(r["arm"], r["n"], r["seed"], r["name"])] = r
    return rows


def ci(x):
    x = np.asarray([v for v in x if v is not None], float)
    if len(x) < 2:
        return (float(x.mean()) if len(x) else None, None, None)
    h = stats.t.ppf(0.975, len(x) - 1) * x.std(ddof=1) / np.sqrt(len(x))
    return float(x.mean()), float(x.mean() - h), float(x.mean() + h)


def fmt(v, nd=3):
    return "" if v is None else f"{v:.{nd}f}"


def mfmt(x, nd=3):
    m, lo, hi = ci(x)
    return fmt(m, nd) + (f" [{fmt(lo, nd)}, {fmt(hi, nd)}]" if lo is not None else "")


def head_for(arm):
    return "own" if arm in ("hints", "lathints", "teacher") else "probe"


def vals(rows, arm, n, seed, mode, get):
    out = []
    for (a, nn, s, _), r in rows.items():
        if a == arm and nn == n and s == seed and mode in r["modes"]:
            out.append(get(r["modes"][mode]))
    return out


def m4(key, head):
    return lambda m: (m.get(head) or {}).get("m4", {}).get(key)


def main():
    rows = load(sys.argv[1])
    print("# Experiment 3 tables\n\nGenerated by `analyze_e3.py` from `results/e3a*/e3/*.json`. Quicksort, TEACH-WRITTEN `best` checkpoints. `s3` is the official-style test set, seed 3; `s20261107` the fresh set. Mean over checkpoints [95% t interval]. Own decoders for `hints`, `lathints` and the teacher; probes for `lat`, `latanneal`, `nohint`.\n")
    print("## Replay gate\n")
    sc = json.load(open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "inputs", "teach_scores.json")))
    diffs = [abs(r["modes"]["F"]["score"] - sc[r["name"]][str(n)]["score"]) for (a, n, s, nm), r in rows.items() if s == 3 and nm in sc]
    print(f"Free-running F1 on seed 3 against each run's `result.json`: {len(diffs)} comparisons, {sum(d == 0 for d in diffs)} exact, {sum(d > 1e-6 for d in diffs)} above 1e-6, largest {max(diffs) if diffs else 0:.5f}.\n")
    print("## Reference trajectories: what the stack means\n\n| n | seed | scan steps | child steps | pop steps | pop share of steps | pop share of interval changes | pops solved by the local rule |\n|---:|---:|---:|---:|---:|---:|---:|---:|")
    for n in SIZES:
        for seed in (3, 20261107):
            r = next((v for k, v in rows.items() if k[1] == n and k[2] == seed), None)
            if r:
                e = r["events"]
                tot = e["scan"] + e["child"] + e["pop"]
                print(f"| {n} | {seed} | {e['scan']} | {e['child']} | {e['pop']} | {e['pop'] / tot:.3f} | {e['pop'] / max(1, e['child'] + e['pop']):.3f} | {e['rule_hits'] / max(1, e['pop']):.3f} |")
    for seed in (3, 20261107):
        print(f"\n## Decomposition, seed {seed}\n")
        print("`read`: reference-fed accuracy where the target does not change (mean of p, r, i, j). `step`: where it changes. `R F1`: output F1 reference-fed, a reading test, since the last reference `pred_h` is the sorted order. `F-all`, `R-all`: accuracy over all steps. `R-F last`: the gap on the last quarter of steps.\n")
        print("| arm | n | seeds | F1 free | F1 R | F1 Z | read | step | F read | F step | F-all | R-all | R-F last | gates failed |\n|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---|")
        for arm in ARMS:
            h = head_for(arm)
            for n in SIZES:
                f = vals(rows, arm, n, seed, "F", lambda m: m["score"])
                if not f:
                    continue
                Rf = vals(rows, arm, n, seed, "R", lambda m: m["score"])
                Zf = vals(rows, arm, n, seed, "Z", lambda m: m["score"])
                rd, st = vals(rows, arm, n, seed, "R", m4("read", h)), vals(rows, arm, n, seed, "R", m4("step", h))
                fr, fs = vals(rows, arm, n, seed, "F", m4("read", h)), vals(rows, arm, n, seed, "F", m4("step", h))
                fa, ra = vals(rows, arm, n, seed, "F", m4("all", h)), vals(rows, arm, n, seed, "R", m4("all", h))
                fl, rl = vals(rows, arm, n, seed, "F", m4("last", h)), vals(rows, arm, n, seed, "R", m4("last", h))
                gap = np.mean(rl) - np.mean(fl) if rl else None
                g = []
                if rd and (np.mean(rd) < 0.9 or np.mean(Rf) < 0.9):
                    g.append("reading")
                if st and np.mean(st) < 0.9:
                    g.append("one step")
                if gap is not None and gap >= 0.1:
                    g.append("keeping")
                print(f"| {arm} | {n} | {len(f)} | {mfmt(f)} | {mfmt(Rf)} | {mfmt(Zf)} | {mfmt(rd)} | {mfmt(st)} | {mfmt(fr)} | {mfmt(fs)} | {mfmt(fa)} | {mfmt(ra)} | {fmt(gap)} | {', '.join(g) or ('n/a' if not rd else 'none')} |")
    print("\n## Per hint, reference-fed, seed 3\n\n| arm | n | hint | read | step | free read | free step |\n|---|---:|---|---:|---:|---:|---:|")
    for arm in ("hints", "lathints", "lat"):
        h = head_for(arm)
        for n in SIZES:
            for k in (*MASKS, "pred_h"):
                g = lambda key: (lambda m: (m.get(h) or {}).get(k, {}).get(key))  # noqa: E731, B023
                print(f"| {arm} | {n} | {k} | {fmt(ci(vals(rows, arm, n, 3, 'R', g('read')))[0])} | {fmt(ci(vals(rows, arm, n, 3, 'R', g('step')))[0])} | {fmt(ci(vals(rows, arm, n, 3, 'F', g('read')))[0])} | {fmt(ci(vals(rows, arm, n, 3, 'F', g('step')))[0])} |")
    print("\n## Where the state is: p and r on each event type, seed 3\n\nShare with both p and r right at the next step. `R - Z` on pop steps is the frozen `stack` read: a difference above 0.1 with an interval over seeds excluding zero counts as a student holding pending ranges.\n")
    print("| arm | n | event | F | R | Z | T | R - Z [95% CI] | stack |\n|---|---:|---|---:|---:|---:|---:|---|---|")
    for arm in ("hints", "lathints", "lat", "latanneal", "teacher"):
        h = head_for(arm)
        for n in SIZES:
            for ev in ("scan", "child", "pop"):
                g = lambda m: (m.get(h) or {}).get("events", {}).get(ev, {}).get("pr")  # noqa: E731, B023
                f, r, z, t = (vals(rows, arm, n, 3, mo, g) for mo in ("F", "R", "Z", "T"))
                if arm == "teacher":
                    t = vals(rows, arm, n, 3, "Rh", g)
                if not r:
                    continue
                d = [a - b for a, b in zip(r, z) if a is not None and b is not None]
                m, lo, hi = ci(d)
                st = ""
                if ev == "pop":
                    st = "yes" if (m is not None and lo is not None and m > 0.1 and lo > 0) else "no"
                print(f"| {arm} | {n} | {ev} | {fmt(ci(f)[0])} | {fmt(ci(r)[0])} | {fmt(ci(z)[0])} | {fmt(ci(t)[0])} | {mfmt(d)} | {st} |")
    print("\n## Matched arms given the teacher's full state (T) and the teacher itself, seed 3\n\n| arm | n | mode | F1 | m4 read | m4 step | m4 all |\n|---|---:|---|---:|---:|---:|---:|")
    for arm, ms in (("lat", ("R", "Z", "T")), ("lathints", ("R", "Z", "T")), ("latanneal", ("R", "Z", "T")), ("teacher", ("F", "R", "Z", "Rh"))):
        h = head_for(arm)
        for n in SIZES:
            for mo in ms:
                print(f"| {arm} | {n} | {mo} | {fmt(ci(vals(rows, arm, n, 3, mo, lambda m: m['score']))[0])} | {fmt(ci(vals(rows, arm, n, 3, mo, m4('read', h)))[0])} | {fmt(ci(vals(rows, arm, n, 3, mo, m4('step', h)))[0])} | {fmt(ci(vals(rows, arm, n, 3, mo, m4('all', h)))[0])} |")
    print("\n## Compounding check, seed 3, `hints` own decoders\n\nSurvival to step t: every one of p, r, i, j right at all steps so far. `predicted` is the product of one-step reference-fed rates; `actual` is free-running.\n")
    print("| n | step | predicted | actual |\n|---:|---:|---:|---:|")
    for n in SIZES:
        cs = [r["curves"]["own"]["compound"] for k, r in rows.items() if k[0] == "hints" and k[1] == n and k[2] == 3 and "own" in r["curves"]]
        if not cs:
            continue
        for i, st in enumerate(cs[0]["step"]):
            pr = [c["predicted"][i] for c in cs if len(c["step"]) > i and c["step"][i] == st]
            ac = [c["actual"][i] for c in cs if len(c["step"]) > i and c["step"][i] == st]
            print(f"| {n} | {st} | {np.mean(pr):.4f} | {np.mean(ac):.4f} |")
    print("\n## Handoff: reference-fed to the handoff, then free-running (H50); and free to the handoff, then reference-fed (B50), seed 3\n\nmean of p, r, i, j at horizon h after the handoff, with R and F on the same steps. Means over checkpoints.\n")
    print("| arm | n | mode | h <= | steps | this mode | R same steps | F same steps |\n|---|---:|---|---:|---:|---:|---:|---:|")
    for arm in ("hints", "lathints", "lat"):
        h = head_for(arm)
        for n in SIZES:
            for mo in ("H50", "B50"):
                acc = {}
                for k, r in rows.items():
                    if k[0] == arm and k[1] == n and k[2] == 3 and h in r["curves"] and mo in r["curves"][h]:
                        for row in r["curves"][h][mo]:
                            acc.setdefault(row[0], []).append(row[1:])
                for hi in sorted(acc):
                    a = np.asarray(acc[hi], float)
                    print(f"| {arm} | {n} | {mo} | {hi} | {int(a[:, 0].mean())} | {a[:, 1].mean():.3f} | {a[:, 2].mean():.3f} | {a[:, 3].mean():.3f} |")


if __name__ == "__main__":
    main()
