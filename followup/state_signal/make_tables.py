"""make_tables.py: regenerate every table from raw JSON and write TABLES.md. Run from this folder: python3 -B make_tables.py"""
import json
import subprocess
import sys


def run(args):
    return subprocess.run([sys.executable, "-B", *args], capture_output=True, text=True, check=True).stdout


parts = ["# WSP-STATE-SIGNAL tables\n\nEvery table below is generated by `make_tables.py` from raw JSON in `results/`. Do not edit by hand.\n"]
open("results/e1_tables.md", "w").write(run(["analyze_e1.py", "results/e1a/e1"]))
open("results/e2_tables.md", "w").write(run(["analyze_e2.py", "tables", "results/e2diag", "results/e2scored"]))
open("results/e3_tables.md", "w").write(run(["analyze_e3.py", "results/e3"]))
open("results/e4_tables.md", "w").write(run(["analyze_e4.py", "results/e4s/scan", "results/e4t/train"]))
open("results/e2_long_tables.md", "w").write(run(["analyze_e2.py", "tables", "results/e2diag", "results/e2long"]).split("## Amendment 3")[1].split("## Frozen reads")[0])
import os
if os.path.isdir("results/e2lr"):
    open("results/e2_sweep_tables.md", "w").write(run(["analyze_e2.py", "sweep", "results/e2lr"]))
for f in ("e1", "e2", "e3", "e4"):
    parts.append(open(f"results/{f}_tables.md").read().replace("\n# ", "\n## ").replace("# Experiment", "## Experiment", 1))
parts.append("## Experiment 2, 1,500-step check of the oracle arms on `anylen` (batch 64)\n" + open("results/e2_long_tables.md").read().split("\n", 1)[1])
if os.path.exists("results/e2_sweep_tables.md"):
    parts.append("## Experiment 2, lr sweep on `anylen` `z1`\n\n" + open("results/e2_sweep_tables.md").read())
g = json.load(open("results/gain.json"))
g2 = json.load(open("results/gain2.json"))
s = ["## Output gain (amendment 1)\n", "Final answer logits times an external alpha, every argmax preserved; `lnf.w` alone scaled; `lnf.w` and `lnf.b` scaled together (exactly alpha times the logits). CE and strict accuracy, length 4 (256 problems), and length 20 (16) for `anylen`.\n",
     "| net | n | alpha | external CE | external strict | lnf.w CE | lnf.w strict | lnf.w+b CE | lnf.w+b strict |\n|---|---:|---:|---:|---:|---:|---:|---:|---:|"]
for net, v in g.items():
    for c in v["cells"]:
        for r in c["rows"]:
            s.append(f"| {net} | {c['n']} | {r['alpha']:g} | {r['external']['ce']:.4f} | {r['external']['strict']:.3f} | {r['lnf_w']['ce']:.4g} | {r['lnf_w']['strict']:.3f} | {r['lnf_w_b']['ce']:.4f} | {r['lnf_w_b']['strict']:.3f} |")
s.append("\nalpha for mean CE 0.01: " + ", ".join(f"{net} n={c['n']} {c['alpha_ce_0_01']:.3f}" for net, v in g.items() for c in v["cells"]) + ". The readout bias holds -j^2 (`anylen`) and a similar quadratic (`two`), so scaling only the gain moves the peak of the quadratic decode and changes the argmax.\n")
s.append("Same scaling on real float32 weights, full forward (`gain2.py`):\n\n| net | alpha | n | strict | CE | min margin | gradient norm | share on zeros | rms on zeros | rms on support |\n|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|")
for net, rows in g2.items():
    for r in rows:
        gr = r.get("grad")
        s.append(f"| {net} | {r['alpha']:g} | {r['n']} | {r['strict']:.3f} | {r['ce']:.4f} | {r['min_margin']:.3f} | " + (f"{gr['norm']:.3g} | {gr['zero_share']:.4f} | {gr['rms_zero']:.3g} | {gr['rms_support']:.3g} |" if gr else " | | | |"))
s.append("\n## Experiment 1 post hoc erasure check (`posthoc_e1.py`)\n\n| net | n | d | alpha | flip | r all | r dynamic | r static | logit change / full change |\n|---|---:|---:|---:|---:|---:|---:|---:|---:|")
for r in json.load(open("results/posthoc_e1.json")):
    s.append(f"| {r['net']} | {r['n']} | {r['d']} | {r['alpha']} | {r['flip']:.3f} | {r['r_all']:.3g} | {r['r_dyn']:.3g} | {r['r_static']:.3g} | {r['logit_change_share']:.2g} |")
parts.append("\n".join(s) + "\n")
open("TABLES.md", "w").write("\n".join(parts))
print("wrote TABLES.md")
