"""analyze.py: TABLES.md and summary.json from the raw JSON in results/, and the scores of P1-P5 by PROTOCOL.md's rules."""
import json
import statistics as st
from collections import defaultdict
from pathlib import Path

H = Path(__file__).resolve().parent
R = H / "results"
TRAINED, WRITTEN = ("ng1", "ng2", "tf"), ("anylen", "two")


def load(*globs):
    out = []
    for g in globs:
        out += [json.loads(p.read_text()) for p in sorted(R.glob(g))]
    return out


def med(xs):
    xs = [x for x in xs if x is not None]
    return st.median(xs) if xs else None


def f(x, d=3):
    if x is None:
        return "-"
    if isinstance(x, bool):
        return str(x)
    if isinstance(x, int):
        return str(x)
    return f"{x:.{d}g}"


def scan_rows(rs):
    g = defaultdict(list)
    for r in rs:
        g[(r["case"]["net"], r["case"]["cond"])].append(r)
    rows = {}
    for (net, cond), xs in sorted(g.items()):
        row = dict(net=net, cond=cond, draws=len(xs), base_ok=all(x["base_ok"] for x in xs), alpha=xs[0]["alpha"],
                   ce0=med([x["ce0"] for x in xs]), g_norm=med([x["g_norm"] for x in xs]), w_norm=xs[0]["w_norm"],
                   cos=med([abs(x["cos_grad_gain"]) for x in xs]))
        for d in sorted(xs[0]["rows"]):
            e = [x["rows"][d]["eps_star"] for x in xs]
            row[d] = dict(eps=med(e), censored=sum(x["rows"][d]["censored"] for x in xs),
                          fail_len={str(k): sum(x["rows"][d]["fail_len"] == k for x in xs) for k in sorted({x["rows"][d]["fail_len"] for x in xs}, key=str)})
        row["R"] = row["grad"]["eps"] / row["rand"]["eps"] if row["rand"]["eps"] else None
        if "own" in row:
            row["R_own"] = row["own"]["eps"] / row["rand"]["eps"]
        if "copy_share" in xs[0]:
            row["copy0_share"] = med([x["copy_share"][0] for x in xs])
            row["copy1plus_share"] = med([sum(x["copy_share"][1:]) for x in xs])
            row["shared_share"] = med([x["shared_share"] for x in xs])
        rows[(net, cond)] = row
    return rows


def cell_key(c):
    if "adam_eps" in c or ("clip" in c):
        return "own"
    return f"{c['opt']} {c['lr']:g}"


def train_rows(rs):
    g = defaultdict(list)
    for r in rs:
        c = r["case"]
        g[(c["net"], c["cond"], cell_key(c))].append(r)
    rows = {}
    for k, xs in sorted(g.items(), key=lambda kv: (kv[0][0], kv[0][1], kv[0][2])):
        rows[k] = dict(seeds=len(xs), survived=sum(x["fail_step"] is None for x in xs), start_ok=all(x["start_ok"] for x in xs),
                       fail_step=med([x["fail_step"] for x in xs]), fail_len=sorted({str(x["fail_len"]) for x in xs if x["fail_step"]}),
                       rel_disp=med([x["rel_disp_ok"] for x in xs]), ce_start=med([x["ce_start"] for x in xs]), ce_ok=med([x["ce_ok"] for x in xs]))
    return rows


def main():
    # g-scan's ng1 cases ran before ng1's length-64 drop and are not used (DECISIONS.md, 08:41 UTC); g-scan-ng1 reruns them.
    s5 = scan_rows(load("c-scan/s5/*.json", "g-scan/s5/s5-ng2-*.json", "g-scan/s5/s5-tf-*.json", "g-scan-ng1/s5/*.json"))
    s6 = scan_rows(load("c-scan/s6/*.json"))
    t5 = train_rows(load("c-train/t5/*.json", "g-train2/t5/*.json"))
    t6 = train_rows(load("c-train/t6/*.json"))
    chk = json.loads((R / "g-check/check.json").read_text()) if (R / "g-check/check.json").exists() else {}
    L = ["# WSP-JOURNEY tables", "", "Generated by `analyze.py` from raw JSON in `results/`. eps* = largest L2 step along a unit direction with every strict problem right; medians over draws.", ""]
    if chk:
        L += ["## Start-of-run check (`g-check`)", "", "| net | strict at start | first failing length | CE at first length | params | ||W|| | low alpha (alpha, CE at alpha, CE at 1) |", "|---|---|---|---:|---:|---:|---|"]
        for k, v in chk.items():
            s = v["strict"]
            L.append(f"| {k} | {s[0]} | {s[1]} | {f(s[2])} | {v['n_params']:,} | {f(v['w_norm'])} | {', '.join(f(x) for x in v['low_alpha']) if 'low_alpha' in v else '-'} |")
        L.append("")
    L += ["## Experiment 5 scan", "", "| net | cond | draws | start ok | alpha | CE | |grad| | ||W|| | |cos(grad, gain)| | eps* grad | eps* rand | eps* gain (censored) | R = grad/rand | eps* own (R_own) | grad fail lengths |",
          "|---|---|---:|---|---:|---:|---:|---:|---:|---:|---:|---|---:|---|---|"]
    for (net, cond), r in s5.items():
        own = f"{f(r['own']['eps'])} ({f(r['R_own'])})" if "own" in r else "-"
        L.append(f"| {net} | {cond} | {r['draws']} | {r['base_ok']} | {f(r['alpha'])} | {f(r['ce0'])} | {f(r['g_norm'])} | {f(r['w_norm'])} | {f(r['cos'])} | {f(r['grad']['eps'])} | {f(r['rand']['eps'])} | {f(r['gain']['eps'])} ({r['gain']['censored']}) | {f(r['R'])} | {own} | {r['grad']['fail_len']} |")
    L += ["", "## Experiment 5 training", "", "| net | cond | cell | survived / seeds | start ok | median fail step | fail lengths | rel. displacement at last pass | CE start | CE at last pass |", "|---|---|---|---|---|---:|---|---:|---:|---:|"]
    for (net, cond, cell), r in t5.items():
        L.append(f"| {net} | {cond} | {cell} | {r['survived']}/{r['seeds']} | {r['start_ok']} | {f(r['fail_step'])} | {r['fail_len']} | {f(r['rel_disp'])} | {f(r['ce_start'])} | {f(r['ce_ok'])} |")
    tied = s5.get(("anylen", "low"))
    L += ["", "## Experiment 6 scan (tied = Experiment 5 anylen low)", "", "| | draws | eps* grad | eps* rand | eps* gain | grad fail lengths | last copy's share of grad^2 | earlier copies | shared |", "|---|---:|---:|---:|---:|---|---:|---:|---:|"]
    for lab, r in (("tied", tied), ("untied", s6.get(("untied", "low")))):
        if r:
            L.append(f"| {lab} | {r['draws']} | {f(r['grad']['eps'])} | {f(r['rand']['eps'])} | {f(r['gain']['eps'])} | {r['grad']['fail_len']} | {f(r.get('copy0_share'))} | {f(r.get('copy1plus_share'))} | {f(r.get('shared_share'))} |")
    L += ["", "## Experiment 6 training", "", "| cell | tied survived | tied median fail step | tied rel. disp | untied survived | untied median fail step | untied rel. disp | untied fail lengths |", "|---|---|---:|---:|---|---:|---:|---|"]
    cells = sorted({k[2] for k in t6}, key=lambda s: (s.split()[0], float(s.split()[1])))
    for cell in cells:
        a, b = t6.get(("anylen", "low", cell)), t6.get(("untied", "low", cell))
        if a and b:
            L.append(f"| {cell} | {a['survived']}/{a['seeds']} | {f(a['fail_step'])} | {f(a['rel_disp'])} | {b['survived']}/{b['seeds']} | {f(b['fail_step'])} | {f(b['rel_disp'])} | {b['fail_len']} |")

    # scores
    sc = {}
    p1 = {f"{n}-{c}": s5[(n, c)]["R"] for n in TRAINED + WRITTEN for c in ("low", "high") if (n, c) in s5}
    sc["P1"] = dict(values=p1, holds=all((v is not None and v >= 1) for k, v in p1.items() if k.split("-")[0] in TRAINED)
                    and all((v is not None and v <= 0.33) for k, v in p1.items() if k.split("-")[0] in WRITTEN), complete=len(p1) == 10)
    p2 = {n: s5[(n, "low")]["cos"] for n in TRAINED + WRITTEN if (n, "low") in s5}
    sc["P2"] = dict(values=p2, holds=all(p2[n] >= 0.1 for n in TRAINED if n in p2) and all(p2[n] <= 1e-6 for n in WRITTEN if n in p2), complete=len(p2) == 5)
    p3t = {f"{n}-{c}-{cell}": t5[(n, c, cell)]["survived"] for n in TRAINED for c in ("low", "high") for cell in ("adam 1e-06", "adam 1e-05", "adam 0.0001", "own") if (n, c, cell) in t5}
    p3w = {f"{n}-{c}-{cell}": t5[(n, c, cell)]["survived"] for n in WRITTEN for c in ("low", "high") for cell in ("adam 1e-06", "adam 1e-05", "adam 0.0001", "adam 0.001") if (n, c, cell) in t5}
    sc["P3"] = dict(trained=p3t, written=p3w, holds=all(v == 3 for v in p3t.values()) and all(v == 0 for v in p3w.values()), complete=len(p3t) == 24 and len(p3w) == 16)
    nodiff = any((s5.get((n, "low"), {}).get("R") or 1) <= 0.33 for n in TRAINED) or any(
        3 - t5[(n, "low", cell)]["survived"] >= 2 for n in TRAINED for cell in ("adam 1e-06", "adam 1e-05", "adam 0.0001") if (n, "low", cell) in t5)
    sc["reading5"] = "keeps own, leaves written" if sc["P1"]["holds"] and sc["P3"]["holds"] else ("no difference" if nodiff else "mixed")
    un = s6.get(("untied", "low"))
    if tied and un:
        ratio = un["grad"]["eps"] / tied["grad"]["eps"]
        not100 = 8 - un["grad"]["fail_len"].get("100", 0)
        sc["P4"] = dict(ratio=ratio, untied_first_fail_not_100=not100, holds=ratio >= 5 and not100 >= 6)
        sc["reading6"] = "loop compounding" if sc["P4"]["holds"] else ("last passes themselves" if ratio < 2 else "mixed")
    sgd = [c for c in cells if c.startswith("sgd")]
    p5 = {c: (t6[("anylen", "low", c)]["survived"], t6[("untied", "low", c)]["survived"]) for c in sgd if ("anylen", "low", c) in t6 and ("untied", "low", c) in t6}
    sc["P5"] = dict(cells=p5, holds=any(u == 3 and t < 3 for t, u in p5.values()))
    L += ["", "## Scores (PROTOCOL.md rules)", "", "```", json.dumps(sc, indent=1), "```", ""]
    (H / "TABLES.md").write_text("\n".join(L))
    (H / "summary.json").write_text(json.dumps(dict(scores=sc), indent=1))
    print("\n".join(L[-40:]))


if __name__ == "__main__":
    main()
